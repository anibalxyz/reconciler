package com.anibalxyz.core;

import java.util.Objects;
import java.util.function.Consumer;
import java.util.function.Function;

/**
 * Represents the result of an operation that can either succeed with a value of type {@code V} or
 * fail with an error of type {@code E}.
 *
 * <p>A {@code Result} is a sealed interface with two record variants: {@link Success} and {@link
 * Failure}.
 *
 * @param <V> the type of the success value
 * @param <E> the type of the failure error
 */
public sealed interface Result<V, E> permits Result.Success, Result.Failure {

  /** Creates a successful {@code Result} with the given value. */
  static <V, E> Result<V, E> success(V value) {
    return new Success<>(value);
  }

  /** Creates a successful {@code Result} with no value. */
  static <E> Result<Void, E> success() {
    return success(null);
  }

  /** Creates a failed {@code Result} with the given error. */
  static <V, E> Result<V, E> failure(E error) {
    return new Failure<>(error);
  }

  boolean isSuccess();

  boolean isFailure();

  default V unwrap() {
    return switch (this) {
      case Failure<V, E>(E error) -> throw UnwrapFailedException.of(error);
      case Success<V, E>(V value) -> value;
    };
  }

  /**
   * Returns the success value if present or throws an exception generated by the provided mapper
   * function.
   *
   * @param exceptionMapper function mapping the error to an exception
   * @param <X> type of exception to throw
   * @return the success value
   * @throws X if this result is a failure
   */
  default <X extends Throwable> V orThrow(Function<? super E, ? extends X> exceptionMapper)
      throws X {
    return switch (this) {
      case Failure<V, E>(E error) -> throw exceptionMapper.apply(error);
      case Success<V, E>(V value) -> value;
    };
  }

  /**
   * Executes the given action if this result is a failure.
   *
   * @param consumer action to execute with the error
   * @return this result
   */
  default Result<V, E> onFailure(Consumer<? super E> consumer) {
    if (this instanceof Failure<V, E>(E error)) {
      consumer.accept(error);
    }
    return this;
  }

  /**
   * Executes the given action if this result is a success.
   *
   * @param consumer action to execute with the success value
   * @return this result
   */
  default Result<V, E> onSuccess(Consumer<? super V> consumer) {
    if (this instanceof Success<V, E>(V value)) {
      consumer.accept(value);
    }
    return this;
  }

  /**
   * Maps the success value using the provided mapper function if present.
   *
   * @param mapper function to transform the success value
   * @param <U> new success value type
   * @return a new result with a transformed success value, or the original error
   */
  default <U> Result<U, E> map(Function<? super V, ? extends U> mapper) {
    return switch (this) {
      case Failure<V, E>(E error) -> Result.failure(error);
      case Success<V, E>(V value) -> Result.success(mapper.apply(value));
    };
  }

  /**
   * Maps the error value using the provided mapper function if present.
   *
   * @param mapper function to transform the error value
   * @param <F> new error value type
   * @return a new result with an original success value, or transformed error
   */
  default <F> Result<V, F> mapError(Function<? super E, ? extends F> mapper) {
    return switch (this) {
      case Failure<V, E>(E error) -> Result.failure(mapper.apply(error));
      case Success<V, E>(V value) -> Result.success(value);
    };
  }

  /**
   * Flat-maps the success value using a function that returns a {@code Result}.
   *
   * @param mapper function to transform the success value into another result
   * @param <U> new success value type
   * @return the result returned by mapper, or the original error
   */
  default <U> Result<U, E> flatMap(Function<? super V, ? extends Result<U, E>> mapper) {
    return switch (this) {
      case Failure<V, E>(E error) -> Result.failure(error);
      case Success<V, E>(V value) -> mapper.apply(value);
    };
  }

  /**
   * Applies {@code onSuccess} if this is a success, or {@code onFailure} if this is a failure.
   *
   * @param onSuccess function to apply to success value
   * @param onFailure function to apply to error value
   * @param <U> return type
   * @return the mapped result of applying the appropriate function
   */
  default <U> U fold(
      Function<? super V, ? extends U> onSuccess, Function<? super E, ? extends U> onFailure) {
    return switch (this) {
      case Success<V, E>(V value) -> onSuccess.apply(value);
      case Failure<V, E>(E error) -> onFailure.apply(error);
    };
  }

  final class UnwrapFailedException extends IllegalStateException {
    private UnwrapFailedException(String message) {
      super(message);
    }

    static UnwrapFailedException of(Object error) {
      return new UnwrapFailedException("Called unwrap() on a Failure Result. Error: " + error);
    }
  }

  /** Represents a successful result containing a value. */
  record Success<V, E>(V value) implements Result<V, E> {
    @Override
    public boolean isSuccess() {
      return true;
    }

    @Override
    public boolean isFailure() {
      return false;
    }
  }

  /** Represents a failed result containing an error. */
  record Failure<V, E>(E error) implements Result<V, E> {
    public Failure {
      Objects.requireNonNull(error, "Failure error cannot be null");
    }

    @Override
    public boolean isSuccess() {
      return false;
    }

    @Override
    public boolean isFailure() {
      return true;
    }
  }
}
